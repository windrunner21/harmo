const digits = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_";
const step = 0.5;
const columns = 360 / step;

let cells: Uint8Array | undefined;

const decode = () => {
  const grid = new Uint8Array(rows.length * columns);
  rows.forEach((row, index) => {
    let at = index * columns;
    let land = false;
    let value = 0;
    let shift = 0;
    for (const char of row) {
      const digit = digits.indexOf(char);
      value += (digit & 31) << shift;
      shift += 5;
      if (digit >= 32) continue;
      if (land) grid.fill(1, at, at + value);
      at += value;
      land = !land;
      value = 0;
      shift = 0;
    }
  });
  return grid;
};

export const isLand = (lat: number, lon: number) => {
  cells ??= decode();
  const row = Math.min(rows.length - 1, Math.max(0, Math.floor((90 - lat) / step)));
  const column = Math.min(columns - 1, Math.max(0, Math.floor((((lon + 180) % 360) + 360) % 360 / step)));
  return cells[row * columns + column] === 1;
};
